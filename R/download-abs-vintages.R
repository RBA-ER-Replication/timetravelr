# Helper Functions --------------------------------------------------------
get_url <- function(vintage_date, release_id, annual) {
  if (annual) {
    year <- format(vintage_date, "%y") |> as.character()
    prev_year <- (as.numeric(format(vintage_date, "%Y")) - 1) |> as.character()
    url <-paste0("https://www.abs.gov.au/AUSSTATS/abs@.nsf/DetailsPage/",
                 release_id, prev_year, "-",year, "?OpenDocument")
  } else {
    month <- format(vintage_date, "%b") |> as.character()
    year <- format(vintage_date, "%Y") |> as.character()
    url <-paste0("https://www.abs.gov.au/AUSSTATS/abs@.nsf/DetailsPage/",
                 release_id, month, "%20",year, "?OpenDocument")
  }
  url
}

clean_name <- function(name) {
  stringr::str_remove_all(name, "[\\t\\.]")
}

parse_downloadurl <- function(download_url) {
  parsed_url <- httr::parse_url(download_url)
  query <- names(parsed_url$query)
  sub_section <- stringr::str_split(parsed_url$path, "/")[[1]][[2]]

  file_name <- query[[2]]
  code <- query[[5]]
  url <- sprintf("https://www.abs.gov.au/ausstats/%s/0/%s/$File/%s",
                 sub_section,
                 code,
                 file_name)
  list(file_name=file_name,
       url=url,
       ext=tools::file_ext(file_name))
}

parse_listentry <- function(listentry) {
  name <- listentry |>
    rvest::html_text2() |>
    clean_name()

  hrefs <- listentry |>
    rvest::html_elements("a") |>
    rvest::html_attr("href")

  icon_descs <- listentry |>
    rvest::html_elements("a") |>
    rvest::html_elements("img") |>
    rvest::html_attr("alt")

  func <- function(icon_desc, href) {
    if (stringr::str_detect(icon_desc, "Download")) {
      parsed <- sprintf("https://www.ausstats.abs.gov.au%s", href) |>
        parse_downloadurl()
      df <- (data.frame(Name=name, Link=parsed$url, FileName=parsed$file_name,
                        FileType=parsed$ext))
    } else {
      df <- NULL
    }
    df
  }
  purrr::map2(icon_descs, hrefs, func) |>
    dplyr::bind_rows()
}

get_files_for_vintage_legacy <- function(vintage_date, cat_no, annual) {
  url <- get_url(vintage_date, cat_no, annual)
  html <- rvest::read_html(url)
  list_entries <- html |>
    rvest::html_elements("#mainpane") |>
    rvest::html_elements(".listentry")
  file_data <- purrr::map(list_entries, function(x) parse_listentry(x)) |>
    dplyr::bind_rows() |>
    dplyr::mutate(Vintage = vintage_date,
                  CatNo = cat_no)
}


# Get list of files  ------------------------------------------------------

get_files_for_vintage <- function(vintage_date, cat_no, annual=FALSE) {
  if (vintage_date > as.Date("2019-06-01")) {
    stop("Vintages past June 2019 are not supported. You can use the readabs
         package to download and read these.")
  } else {
    file_data <- get_files_for_vintage_legacy(vintage_date, cat_no, annual=annual)
  }
  file_data
}

#' Retrieve a list of available files to download from the ABS website.
#' @param vintage_dates List of vintage dates to search for available files in.
#' @param cat_no ABS catalogue number.
#' @param annual Use for annual releases such as annual national accounts. If TRUE,
#' each vintage date corresponds to the END OF YEAR.
#' @export
ABS.find_files <- function(vintage_dates, cat_no, annual=FALSE) {
  purrr::map(vintage_dates, purrr::partial(get_files_for_vintage,
                                           cat_no=cat_no,
                                           annual=annual)) |>
    dplyr::bind_rows()

}

# Download files from the ABS ---------------------------------------------
download_absfile <- function(row, download_dir, vintage_dir=FALSE, cat_dir=FALSE, vintage_prefix=FALSE) {
  name <- row$FileName
  file_type <- row$FileType
  link <- row$Link
  vintage <- as.character(row$Vintage)
  cat_no <- as.character(row$CatNo)

  if (file_type == "pdf") {
    warning("Unable to download pdf files.")
    return(NULL)
  }

  # Save the file into a subdirectory with the vintage name.
  if (vintage_dir) {
    vintage_dirname <- sprintf("%s/%s", download_dir, vintage)
    if(!dir.exists(vintage_dirname)) {
      dir.create(vintage_dirname)
    }
    download_dir <- vintage_dirname
  }

  # Save the file into a subdirectory with the cat name
  if (cat_dir) {
    cat_dirname <- sprintf("%s/%s", download_dir, cat_no)
    if(!dir.exists(cat_dirname)) {
      dir.create(cat_dirname)
    }
    download_dir <- cat_dirname
  }

  # Add the vintage to the front of the file name.
  if (vintage_prefix) {
    name <- sprintf("%s_%s", vintage, name)
  }

  # mode = wb needed for windows
  download.file(link, paste0(download_dir, "/", name), mode = "wb")
}

#' Given a data.frame of files to download (as generated by ABS.find_files),
#' download those files from the ABS website.
#' @param data data.frame containing files to download. This data.frame can be
#' generated using ABS.find_files()
#' @param download_dir directory to download the files to.
#' @param vintage_dir If TRUE, create a directory for each vintage. Default TRUE
#' @param cat_dir If TRUE, save files within a directory for the files catalogue number.
#' @export
ABS.download_files <- function(data, download_dir="./",
                              vintage_dir=TRUE,
                              cat_dir=TRUE,
                              vintage_prefix=FALSE) {
  if (nrow(data) == 0) {
    stop("No rows in input data")
  }
  split(data, 1:nrow(data)) |>
    purrr::map(purrr::partial(download_absfile,
                              download_dir=download_dir,
                              vintage_dir=vintage_dir,
                              cat_dir=cat_dir,
                              vintage_prefix=vintage_prefix))
}
